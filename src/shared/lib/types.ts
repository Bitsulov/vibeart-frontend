/**
 * Описывает тело ошибки, возвращаемое сервером в ответах API.
 */
export interface AppError {
    /** HTTP-код статуса ошибки. */
    statusCode: number;
    /** Сообщение об ошибке. */
    message: string;
    /** Путь запроса, на котором произошла ошибка. */
    path: string;
    /** Дата и время возникновения ошибки в формате ISO 8601. */
    timestamp: string;
}

/**
 * Параметры постраничного запроса к API.
 */
export interface Pageable {
    /** Номер запрашиваемой страницы, начиная с 0. */
    page?: number;
    /** Размер страницы. */
    size?: number;
    /** Поле и направление сортировки в формате `"поле,asc"` или `"поле,desc"`. */
    sort?: string;
}

/**
 * Постраничный ответ API.
 */
export interface Page<T> {
    /** Элементы текущей страницы. */
    content: T[];
    /** Номер текущей страницы, начиная с 0. */
    number: number;
    /** Размер страницы. */
    size: number;
    /** Общее количество элементов на всех страницах. */
    totalElements: number;
    /** Общее количество страниц. */
    totalPages: number;
    /** Признак первой страницы. */
    first: boolean;
    /** Признак последней страницы. */
    last: boolean;
    /** Признак отсутствия элементов. */
    empty: boolean;
}
